#!/bin/bash
# Lists every file in a built bundle with the notice that covers it, and fails
# on a file nothing accounts for.
#
#   Tools/audit-bundle-notices.sh "Retouch Studio.app"
#
# This is an ownership audit, not an existence check: a font can be present
# while the notice never names it, and a notice can name a component the
# bundle does not carry. Both are failures here. The checker only reads the
# bundle; it never modifies or signs it.
set -euo pipefail
cd "$(dirname "$0")/.."

APP="${1:?usage: Tools/audit-bundle-notices.sh <bundle>}"
[ -d "$APP" ] || { echo "✗ bundle not found: $APP" >&2; exit 1; }

RES="$APP/Contents/Resources"
NOTICES="$RES/THIRD_PARTY_NOTICES.txt"
failures=0
fail() { echo "  ✗ $*" >&2; failures=$((failures + 1)); }
files=0
fonts=0

printf '  %-38s %s\n' "OWNER" "FILE"

while IFS= read -r -d '' file; do
  rel="${file#"$APP"/}"
  files=$((files + 1))
  case "$rel" in
    Contents/_CodeSignature/*)
      owner="own (code signature)" ;;
    Contents/MacOS/*)
      owner="own (project source)" ;;
    Contents/Info.plist|Contents/PkgInfo)
      owner="own (bundle metadata)" ;;
    Contents/Resources/LICENSE)
      owner="own (MIT licence text)" ;;
    Contents/Resources/THIRD_PARTY_NOTICES.txt)
      owner="own (this notice)" ;;
    Contents/Resources/AppIcon.icns)
      owner="own (generated by make-icon.sh)" ;;
    Contents/Resources/model-catalog.json)
      owner="own (project data)" ;;
    Contents/Resources/Fonts/OFL.txt)
      owner="Vazirmatn (SIL OFL 1.1 text)" ;;
    Contents/Resources/Fonts/Vazirmatn-*.ttf)
      fonts=$((fonts + 1))
      owner="Vazirmatn (SIL OFL 1.1)"
      if [ ! -f "$NOTICES" ] \
         || ! grep -Fq "$(basename "$file")" "$NOTICES"; then
        fail "Contents/Resources/THIRD_PARTY_NOTICES.txt does not name $rel"
      fi ;;
    Contents/Resources/Worker/*)
      owner="AI helper runtime (its own notices)" ;;
    *)
      owner="" ;;
  esac
  if [ -z "$owner" ]; then
    fail "no notice accounts for $rel"
    printf '  %-38s %s\n' "UNATTRIBUTED" "$rel" >&2
  else
    printf '  %-38s %s\n' "$owner" "$rel"
  fi
done < <(find "$APP" -type f -print0 | sort -z)

# A notice may not claim a component the bundle does not carry.
if [ -f "$NOTICES" ]; then
  if grep -qi 'Vazirmatn' "$NOTICES" && [ "$fonts" -eq 0 ]; then
    fail "the notice names Vazirmatn, but the bundle carries no Vazirmatn font"
  fi
  if [ "$fonts" -gt 0 ] && [ ! -f "$RES/Fonts/OFL.txt" ]; then
    fail "the Vazirmatn fonts ship without Contents/Resources/Fonts/OFL.txt"
  fi
fi

if [ -d "$RES/Worker" ]; then
  [ -f "$RES/Worker/LICENSE" ] \
    || fail "the bundled AI helper carries no Contents/Resources/Worker/LICENSE"
  [ -f "$RES/Worker/THIRD_PARTY_NOTICES.md" ] \
    || fail "the bundled AI helper carries no Contents/Resources/Worker/THIRD_PARTY_NOTICES.md"
fi

if [ "$failures" -ne 0 ]; then
  echo "✗ notice audit found $failures problem(s)" >&2
  exit 1
fi
echo "  ✓ notice audit: $files file(s) accounted for, $fonts Vazirmatn font(s)"
