using System.Text;

namespace RetouchStudio.Imaging;

/// <summary>
/// A complete ICC v2 display profile for sRGB, generated in code.
///
/// Every pixel this host decodes is converted to sRGB, so an exported file
/// whose container declares nothing is read back as sRGB only by convention.
/// Embedding this profile makes the space explicit without depending on a
/// binary fixture or on a system profile whose location varies. The bytes are
/// deterministic: one fixed date and no identifiers, so the same profile is
/// written by every build and can be compared byte for byte.
/// </summary>
public static class SrgbProfile
{
    /// <summary>The profile bytes written into an export.</summary>
    public static readonly byte[] Bytes = Build();

    /// <summary>The name a person sees in a colour picker.</summary>
    public const string Description = "sRGB (Retouch Studio)";

    // D50-adapted sRGB colourants, the values the ICC sRGB profile carries.
    private static readonly (double X, double Y, double Z) White = (0.964202881, 1.0, 0.824905396);

    private static readonly (double X, double Y, double Z)[] Colourants =
    {
        (0.436065674, 0.222488403, 0.013916016),
        (0.385147095, 0.716873169, 0.097076416),
        (0.143066406, 0.060607910, 0.714096069),
    };

    private const int CurveCount = 1024;

    private static byte[] Build()
    {
        var tags = new (string Signature, byte[] Data)[]
        {
            ("desc", DescriptionTag()),
            ("cprt", TextTag("No copyright. Generated by Retouch Studio.\0")),
            ("wtpt", XyzTag(White)),
            ("rXYZ", XyzTag(Colourants[0])),
            ("gXYZ", XyzTag(Colourants[1])),
            ("bXYZ", XyzTag(Colourants[2])),
            ("rTRC", CurveTag()),
            ("gTRC", CurveTag()),
            ("bTRC", CurveTag()),
        };

        var tableSize = 4 + tags.Length * 12;
        var offsets = new int[tags.Length];
        var size = 128 + tableSize;
        for (var i = 0; i < tags.Length; i++)
        {
            size = Align4(size);
            offsets[i] = size;
            size += tags[i].Data.Length;
        }

        var profile = new byte[size];
        WriteU32(profile, 0, (uint)size);
        WriteU32(profile, 8, 0x02100000);            // ICC v2.1
        Encoding.ASCII.GetBytes("mntr").CopyTo(profile, 12);
        Encoding.ASCII.GetBytes("RGB ").CopyTo(profile, 16);
        Encoding.ASCII.GetBytes("XYZ ").CopyTo(profile, 20);
        // 2026-01-01 00:00:00, fixed so the bytes never depend on the build.
        WriteU16(profile, 24, 2026);
        WriteU16(profile, 26, 1);
        WriteU16(profile, 28, 1);
        Encoding.ASCII.GetBytes("acsp").CopyTo(profile, 36);
        WriteS15(profile, 68, White.X);              // PCS illuminant, D50
        WriteS15(profile, 72, White.Y);
        WriteS15(profile, 76, White.Z);

        WriteU32(profile, 128, (uint)tags.Length);
        for (var i = 0; i < tags.Length; i++)
        {
            var entry = 132 + i * 12;
            Encoding.ASCII.GetBytes(tags[i].Signature).CopyTo(profile, entry);
            WriteU32(profile, entry + 4, (uint)offsets[i]);
            WriteU32(profile, entry + 8, (uint)tags[i].Data.Length);
            tags[i].Data.CopyTo(profile, offsets[i]);
        }
        return profile;
    }

    private static byte[] DescriptionTag()
    {
        var text = Encoding.ASCII.GetBytes(Description + "\0");
        var tag = new MemoryStream();
        Write(tag, Encoding.ASCII.GetBytes("desc"));
        WriteU32(tag, 0);
        WriteU32(tag, (uint)text.Length);
        tag.Write(text);
        WriteU32(tag, 0);        // Unicode language code: unused
        WriteU32(tag, 0);        // Unicode string: unused
        WriteU16(tag, 0);        // ScriptCode code: unused
        tag.WriteByte(0);        // ScriptCode count
        tag.Write(new byte[67]);
        return tag.ToArray();
    }

    private static byte[] TextTag(string text)
    {
        var bytes = Encoding.ASCII.GetBytes(text);
        var tag = new MemoryStream();
        Write(tag, Encoding.ASCII.GetBytes("text"));
        WriteU32(tag, 0);
        tag.Write(bytes);
        return tag.ToArray();
    }

    private static byte[] XyzTag((double X, double Y, double Z) value)
    {
        var tag = new byte[20];
        Encoding.ASCII.GetBytes("XYZ ").CopyTo(tag, 0);
        WriteS15(tag, 8, value.X);
        WriteS15(tag, 12, value.Y);
        WriteS15(tag, 16, value.Z);
        return tag;
    }

    /// <summary>
    /// The sRGB transfer curve as a sampled table: encoded input on the axis,
    /// linear light in the samples, which is how a matrix/TRC profile states
    /// its tone response. A single gamma would be wrong for sRGB's toe.
    /// </summary>
    private static byte[] CurveTag()
    {
        var tag = new byte[12 + CurveCount * 2];
        Encoding.ASCII.GetBytes("curv").CopyTo(tag, 0);
        WriteU32(tag, 8, CurveCount);
        for (var i = 0; i < CurveCount; i++)
        {
            var encoded = (double)i / (CurveCount - 1);
            var linear = encoded <= 0.04045
                ? encoded / 12.92
                : Math.Pow((encoded + 0.055) / 1.055, 2.4);
            WriteU16(tag, 12 + i * 2, (ushort)Math.Round(linear * 65535));
        }
        return tag;
    }

    private static int Align4(int value) => (value + 3) & ~3;

    private static void Write(Stream stream, byte[] bytes) => stream.Write(bytes);

    private static void WriteU16(byte[] bytes, int offset, ushort value)
    {
        bytes[offset] = (byte)(value >> 8);
        bytes[offset + 1] = (byte)value;
    }

    private static void WriteU32(byte[] bytes, int offset, uint value)
    {
        bytes[offset] = (byte)(value >> 24);
        bytes[offset + 1] = (byte)(value >> 16);
        bytes[offset + 2] = (byte)(value >> 8);
        bytes[offset + 3] = (byte)value;
    }

    private static void WriteU32(Stream stream, uint value) =>
        stream.Write(new[]
        {
            (byte)(value >> 24), (byte)(value >> 16), (byte)(value >> 8), (byte)value,
        });

    private static void WriteU16(Stream stream, ushort value) =>
        stream.Write(new[] { (byte)(value >> 8), (byte)value });

    private static void WriteS15(byte[] bytes, int offset, double value) =>
        WriteU32(bytes, offset, (uint)(int)Math.Round(value * 65536));
}
